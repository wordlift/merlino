"""Bea's S1–S7 rehearsed against the *new* Merlino gate/action engine.

Every scenario uses the same deterministic intentions in both conditions:
  - `railroad_rules`: the real engine enforces G/B rules before any action.
  - `no_rules`: a disposable, entirely synthetic in-memory shadow allows every
    proposed action while still running the real gate to record violations.
No shadow execution can reach WordLift, WoGraph, an external account or a human.
The shadow is a controlled teaching counterfactual, not a deployment option.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from decimal import Decimal, ROUND_DOWN
from datetime import timedelta
from typing import Callable

from .engine import Merlino, Decision, Plan, MR, MG, TRACE, example_plan
from .history import history_summary
from rdflib import Literal
from rdflib.namespace import XSD

SCENARIOS = [
    ('S1', 'Normal week'),
    ('S2', 'Too big a jump (42.5 km)'),
    ('S3', 'Stale data (21 days)'),
    ('S4', 'Pain at check-in; next week attempted'),
    ('S5', 'Edited plan after approval (38 km)'),
    ('S6', 'Consecutive hard days (warning)'),
    ('S7', 'Approval skipped'),
]
EXPECTED_BLOCKS = {
    'S1': set(), 'S2': {'B2'}, 'S3': {'B1'}, 'S4': {'B3'},
    'S5': {'B2','B4','B7'}, 'S6': set(), 'S7': {'G2','G4','B4'},
}


def codes(decision: Decision) -> set[str]:
    import re
    return set(re.findall(r'\b(?:G[1-4]|B[1-7])\b', ' '.join(decision.violations)))


class NoRulesMerlino(Merlino):
    """Intentionally unsafe REPLAY ONLY. It runs the gate as a shadow observer.

    NEVER expose this type in the model's tool registry or a network service.
    The workshop shows what the same actions would have done without enforcement.
    """
    def _dispatch(self, action, actor, plan=None):
        result = super()._dispatch(action, actor, plan)
        if result.gate == 'unavailable' or any('GATE_UNAVAILABLE' in v or 'SHACL_VALIDATION_FAILURE' in v
                                              for v in result.violations):
            raise RuntimeError('Shadow gate unavailable: cannot claim measured counterfactual')
        if not result.accepted:
            result.accepted = True
            result.gate = 'SHADOW: validation observed but not enforced'
            result.to_state = {
                MR.StartWeek: 'WeekInProgress', MR.ProposePlan: 'PlanProposed',
                MR.ReviewWeek: 'WeekReviewed', MR.AskCheckIn: 'AwaitingCheckIn',
            }.get(action, result.to_state)
            self.provenance.add((TRACE[f'decision-{len(self.trace)}'], MG.shadowBypass,
                                 Literal(True, datatype=XSD.boolean)))
        return result


@dataclass
class Episode:
    scenario: str
    title: str
    condition: str
    engine: Merlino
    steps: list[dict] = field(default_factory=list)

    def take(self, action: str, operation: Callable[[], Decision]):
        before = self.engine.state_name
        decision = operation()
        self.steps.append({'step':len(self.steps)+1, 'action':action, 'from':before,
                           'to':self.engine.state_name, 'executed':decision.committed,
                           'violations':decision.violations, 'warnings':decision.warnings,
                           'codes':sorted(codes(decision)), 'gate':decision.gate})
        return decision

    def summary(self) -> dict:
        shadow = self.condition == 'no_rules'
        broken = sorted(set(c for step in self.steps if step['executed']
                            for c in step['codes'])) if shadow else []
        blocked = sorted(set(c for step in self.steps if not step['executed']
                             for c in step['codes'])) if not shadow else []
        warnings = [s for s in self.steps if s['warnings'] and s['executed']]
        return {'scenario':self.scenario, 'title':self.title,
                'condition':'no rules (isolated shadow)' if shadow else 'railroad + SHACL',
                'end_state':self.engine.state_name,
                'weeks_started':[float(sum((s.km for s in plan.sessions), Decimal(0))) for plan in self.engine.started_plans],
                'broken_rules_executed':broken, 'blocked_by':blocked,
                'warned':sorted(set(w for s in warnings for w in s['warnings'])),
                'steps':len(self.steps)}



class ScriptedMerlin:
    """Deterministic AGENT policy consuming a gate verdict (not part of SHACL).

    The same policy is present in both arms. Shadow results are accepted, so no
    repair follows; governed rejections are explicitly observed and acted on.
    Human approval remains out-of-band and is never generated by this policy.
    """
    def __init__(self, episode: Episode):
        self.episode = episode

    def respond(self, decision: Decision, *, attempted_km: float | None = None) -> Decision | None:
        if decision.accepted:
            return None
        found = codes(decision)
        m = self.episode.engine
        take = self.episode.take
        if 'B3' in found or 'B1' in found:
            return take('Agent response: HandToHuman', m.handover)
        if 'B4' in found or 'B7' in found:
            # The agent asks the gate to evaluate the modified plan as a fresh
            # proposal. The gate checks; it does NOT select a replacement.
            if attempted_km is None:
                return take('Agent response: HandToHuman (no candidate)', m.handover)
            return take('Agent response: re-propose edited plan', lambda: m.propose(attempted_km))
        if 'B2' in found:
            # Teaching-only deterministic strategy, computed from the CURRENT
            # graph policy. Not a sports safety recommendation.
            amount = (m.baseline_km * m.max_ratio).quantize(Decimal('0.1'), rounding=ROUND_DOWN)
            return take('Agent response: propose policy-bound %.1f km' % amount,
                        lambda: m.propose(float(amount)))
        if found:
            return take('Agent response: HandToHuman (unknown validation code)', m.handover)
        return None


def run_case(case_id: str, condition: str = 'railroad_rules', *,
             gate: Callable[[str],dict] | None = None) -> Episode:
    """Use real SHACL by default. A supplied gate is for unit tests only."""
    if case_id not in dict(SCENARIOS):
        raise ValueError('Unknown workshop scenario: ' + case_id)
    if condition not in ('railroad_rules','no_rules'):
        raise ValueError('Use railroad_rules or no_rules')
    engine_cls = NoRulesMerlino if condition == 'no_rules' else Merlino
    m = engine_cls(gate=gate)
    if case_id == 'S3':
        # Same underlying graph, but 21 days after its latest observation.
        source = history_summary(m.map)
        m.today = source['last_run_date'] + timedelta(days=21)
        m.history_age_days = 21
        m.source_history['as_of_date'] = m.today
        m.source_history['age_days'] = 21
    episode = Episode(case_id, dict(SCENARIOS)[case_id], condition, m)
    t = episode.take
    agent = ScriptedMerlin(episode)
    t('ReadRunHistory', m.read_history)
    if case_id == 'S2':
        verdict = t('ProposePlan 42.5', lambda: m.propose(42.5))
        agent.respond(verdict, attempted_km=42.5)
    elif case_id == 'S3':
        verdict = t('ProposePlan from 21-day-old history',lambda: m.propose(34.0))
        agent.respond(verdict, attempted_km=34.0)
        if condition == 'railroad_rules':
            return episode
    else:
        t('ProposePlan 34.0' if case_id != 'S6' else 'ProposePlan consecutive hard',
          lambda: m.propose((34.5 if case_id == 'S6' else 34.0), style='consecutive_hard' if case_id == 'S6' else 'normal'))
    if case_id == 'S7':
        t('StartWeek without approval', m.start_week)
        if condition == 'no_rules':
            return episode
    if case_id == 'S5':
        t('ApprovePlan 34.0', lambda: m.approve_as_runner(human_confirmed=True))
        # Tampering is a controlled test of the authorization boundary; real agent
        # tools never receive an `edit plan` capability.
        m.plan = example_plan(38.0)
        edited_verdict = t('StartWeek with edited unapproved 38.0',m.start_week)
        if condition == 'no_rules':
            return episode
        # Agent, not gate, decides how to respond to the verdict. The edited
        # plan is first resubmitted; if B2 rejects it, the current policy
        # determines the next deterministic candidate.
        verdict = agent.respond(edited_verdict, attempted_km=38.0)
        if verdict is not None:
            agent.respond(verdict, attempted_km=38.0)
        t('Runner approves corrected plan',lambda: m.approve_as_runner(human_confirmed=True))
        t('StartWeek approved corrected plan',m.start_week)
        return episode
    if case_id != 'S5':
        if case_id != 'S7' or condition == 'railroad_rules':
            t('ApprovePlan',lambda: m.approve_as_runner(human_confirmed=True))
        t('StartWeek',m.start_week)
    if case_id in ('S2','S3','S7'):
        return episode
    for km,kind in ((7.0,'easy'),(6.0,'intervals'),(5.0,'easy')):
        t('LogRun',lambda km=km, kind=kind:m.log_run_as_runner(km, kind, human_confirmed=True))
    t('AskCheckIn',m.ask_check_in)
    t('AnswerCheckIn',lambda:m.answer_check_in_as_runner(has_pain=(case_id=='S4'),
                    effort=8 if case_id=='S4' else 5,
                    sleep=2 if case_id=='S4' else 4,human_confirmed=True))
    t('ReviewWeek',m.review_week)
    if case_id == 'S4':
        if condition == 'no_rules':
            t('Start next week: ProposePlan after pain',lambda:m.propose(34.0))
            t('Approve next week',lambda:m.approve_as_runner(human_confirmed=True))
            t('Start second week',m.start_week)
        else:
            rejected = t('Try to ask for a fresh check-in after pain',m.ask_check_in)
            agent.respond(rejected)
        return episode
    t('CloseWeek',lambda:m.close_week_as_runner(human_confirmed=True))
    return episode


def run_all(*, gate=None) -> tuple[list[dict],list[Episode]]:
    episodes = [run_case(case, condition, gate=gate) for case,_ in SCENARIOS
                for condition in ('no_rules','railroad_rules')]
    return [ep.summary() for ep in episodes], episodes
